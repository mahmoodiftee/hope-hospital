// ── Helper ─────────────────────────────────────────────────────────────────
const sleep = (ms) => new Promise(resolve => setTimeout(resolve, ms));

// ── Main patcher ───────────────────────────────────────────────────────────
async function patch() {
    console.log(`🌱 Patching ${translations.length} doctors with Bengali translations...\n`);

    let success = 0;
    let failed = 0;

    for (const doc of translations) {
        const { $id, ...fields } = doc;
        try {
            await db.updateDocument(
                DATABASE_ID,
                DOCTORS_COLLECTION_ID,
                $id,
                fields  // only patches _bn fields, leaves everything else untouched
            );
            console.log(`✅  ${fields.name_bn} (${$id})`);
            success++;
        } catch (err) {
            console.error(`❌  Failed ${$id}:`, err.message);
            failed++;
        }
        await sleep(200); // avoid rate limiting
    }

    console.log(`\n🎉 Done! ${success} updated, ${failed} failed.`);
}

patch();
